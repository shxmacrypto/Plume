import os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fex import *

d = fixture(big=3000)
x = Fex(d)
check = Checks()
try:
    s = x.wait()
    check("opens the folder from the command line", s["loc"] == d, s["loc"])
    check("folders first, natural order", s["visible"][:7] == ["Alpha", "beta", "Gamma", ".secret", "a1.txt", "a2.txt", "a10.txt"], s["visible"])
    check("sidebar has places and drive", "This PC" in s["nav"] and any("(C:)" in n for n in s["nav"]), s["nav"])
    x.shot("browse-a")
    # selection with the mouse
    x.click("Row(4)")
    s = x.state(); check("click selects one", s["sel"] == ["a1.txt"] and s["focus"] == 4, s["sel"])
    x.click("Row(6)", shift=True)
    s = x.state(); check("shift+click selects a range", s["sel"] == ["a1.txt", "a2.txt", "a10.txt"], s["sel"])
    x.click("Row(8)", ctrl=True)
    s = x.state(); check("ctrl+click adds", s["sel_count"] == 4 and s["sel_size"] == 10 + 2000 + 300 + 1234, (s["sel"], s["sel_size"]))
    x.click("Row(5)", ctrl=True)
    s = x.state(); check("ctrl+click removes", "a2.txt" not in s["sel"] and s["sel_count"] == 3, s["sel"])
    x.shot("browse-b")
    x.click("List")
    s = x.state(); check("click in the empty area clears", s["sel_count"] == 0, s["sel"])
    # keyboard
    x.key(VK["HOME"]); x.key(VK["DOWN"])
    s = x.state(); check("arrow keys move", s["sel"] == ["beta"], s["sel"])
    x.key(VK["DOWN"], shift=True); x.key(VK["DOWN"], shift=True)
    s = x.state(); check("shift+arrows extend", s["sel"] == ["beta", "Gamma", ".secret"], s["sel"])
    x.key(VK["END"]); s = x.state(); check("End goes to the last item", s["focus"] == s["rows"] - 1 and s["sel"] == ["Zed.bin"], s["sel"])
    x.key(VK["HOME"]); x.key(L("A"), ctrl=True)
    s = x.state(); check("Ctrl+A selects all", s["sel_count"] == s["rows"] == 11, (s["sel_count"], s["rows"]))
    x.key(VK["ESC"]); s = x.state(); check("Esc clears", s["sel_count"] == 0)
    x.chars("ph"); s = x.state(); check("typing jumps to a name", s["sel"] == ["photo.png"], s["sel"])
    time.sleep(1.1)
    x.chars("a"); s1 = x.state(); x.chars("a"); s2 = x.state()
    check("same letter cycles", s1["sel"] != s2["sel"] and s2["sel"][0].lower().startswith("a"), (s1["sel"], s2["sel"]))
    # open a folder, history
    x.dbl("Row(0)"); s = x.wait()
    check("double-click enters the folder", s["loc"].endswith("Alpha") and s["visible"] == ["Inner", "inside.txt"], (s["loc"], s["visible"]))
    check("back is possible", s["can_back"] and not s["can_forward"])
    x.click("Back"); s = x.wait()
    check("Back returns and reselects", s["loc"] == d and s["sel"] == ["Alpha"], (s["loc"], s["sel"]))
    x.click("Forward"); s = x.wait(); check("Forward", s["loc"].endswith("Alpha"))
    x.key(VK["UP"], alt=True); s = x.wait(); check("Alt+Up goes to the parent and selects the child", s["loc"] == d and s["sel"] == ["Alpha"], s["sel"])
    # big folder + scrolling
    x.key(VK["DOWN"]); x.key(VK["DOWN"]); x.key(VK["ENTER"]); s = x.wait()
    check("Enter opens the folder", s["loc"].endswith("Gamma") and s["rows"] == 3000, (s["loc"], s["rows"]))
    print("     3000 files listed in %.1f ms" % s["took_ms"])
    x.mouse("wheel", "List", dy=-5); time.sleep(0.4); s = x.state()
    check("wheel scrolls", s["scroll"] > 300, s["scroll"])
    x.key(VK["END"]); s = x.state(); check("End scrolls to the bottom", abs(s["scroll"] - s["max_scroll"]) < 1 and s["sel"] == ["file02999.dat"], (s["scroll"], s["max_scroll"]))
    x.shot("browse-c")
    # sorting
    x.nav(d)
    x.click("Header(Size)"); s = x.state()
    check("sort by size, biggest first", s["sort"] == "Size" and not s["asc"] and s["visible"][0] == "Zed.bin", s["visible"])
    x.click("Header(Size)"); s = x.state(); check("click again reverses", s["asc"] and s["visible"][:3] == ["Alpha", "beta", "Gamma"], s["visible"])
    x.click("Header(Name)")
    # search field filters the folder
    x.click("Search"); s = x.state(); check("search field opens", s["edit"] == "Search", s["edit"])
    x.edit("a1"); s = x.state(); check("typing filters", s["visible"] == ["a1.txt", "a10.txt"], s["visible"])
    x.shot("browse-d")
    x.editkey(VK["ENTER"]); s = x.state(); check("Enter moves to the results", s["edit"] is None and s["sel"] == ["a1.txt"], (s["edit"], s["sel"]))
    x.key(VK["ESC"]); s = x.state(); check("Esc clears the filter", s["filter"] == "" and s["rows"] == 11, (s["filter"], s["rows"]))
    # address bar
    x.key(L("L"), ctrl=True); s = x.state(); check("Ctrl+L edits the address", s["edit"] == "Address" and s["edit_text"] == d, (s["edit"], s["edit_text"]))
    x.shot("browse-e")
    x.edit(r"C:\Windows\Fonts\.."); x.editkey(VK["ENTER"]); s = x.wait()
    check("typed address is normalised and opened", s["loc"] == r"C:\Windows", s["loc"])
    x.key(L("L"), ctrl=True); x.edit(r"C:\nope\nothing"); x.editkey(VK["ENTER"]); s = x.state()
    check("wrong address shows a message", s["toast"] and "nope" in s["toast"] and s["loc"] == r"C:\Windows", s["toast"])
    x.shot("browse-f")
    # breadcrumb and sidebar
    x.click("Crumb(0)"); s = x.wait(); check("breadcrumb: This PC", s["loc"] == "pc" and s["rows"] >= 1, s["loc"])
    x.click("Nav(1)"); s = x.wait(); check("sidebar opens Downloads", s["loc"].lower().endswith("downloads"), s["loc"])
    # tabs
    x.key(L("T"), ctrl=True); s = x.wait(); check("Ctrl+T opens a tab", len(s["tabs"]) == 2 and s["cur"] == 1 and s["loc"] == "pc", s["tabs"])
    x.click("Tab(0)"); s = x.state(); check("click switches tab", s["cur"] == 0 and s["loc"].lower().endswith("downloads"))
    x.shot("browse-g")
    x.key(L("W"), ctrl=True); s = x.state(); check("Ctrl+W closes the tab", len(s["tabs"]) == 1 and s["loc"] == "pc", s["tabs"])
finally:
    x.close()
check.done()
