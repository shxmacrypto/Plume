import os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fex import *

d = fixture("fixture4")
x = Fex(d, port=47814)
check = Checks()
try:
    s = x.wait()
    # dragging a selection (recorded only: the test build never starts a real drag)
    x.click("Row(4)"); x.click("Row(5)", ctrl=True)
    p = x.mouse("down", "Row(4)")
    x.cmd("mouse", type="move", x=p["x"] + 30, y=p["y"] + 12)
    dragged = x.cmd("last_drag")
    check("dragging a selected file drags the whole selection", [os.path.basename(q) for q in dragged] == ["a1.txt", "a2.txt"], dragged)
    x.cmd("mouse", type="up", x=p["x"] + 30, y=p["y"] + 12)
    s = x.state()
    check("selection kept after a drag", s["sel"] == ["a1.txt", "a2.txt"] and s["drag"] == "None", (s["sel"], s["drag"]))
    # dragging an unselected file drags it alone
    p = x.mouse("down", "Row(8)")
    x.cmd("mouse", type="move", x=p["x"] + 30, y=p["y"] + 12)
    dragged = x.cmd("last_drag")
    x.cmd("mouse", type="up", x=p["x"] + 30, y=p["y"] + 12)
    check("dragging an unselected file drags it alone", [os.path.basename(q) for q in dragged] == ["notes.md"], dragged)
    # pressing in the empty part of a row then moving draws a selection rectangle instead
    x.click("List")
    p = x.mouse("down", "Row(5)", blank=True)
    x.cmd("mouse", type="move", x=p["x"] - 10, y=p["y"] + 60)
    s = x.state()
    check("rubber band from the empty part of a row", s["drag"] == "Lasso" and s["sel"] == ["a2.txt", "a10.txt", "data.json"], (s["drag"], s["sel"]))
    x.shot("dragdrop-lasso")
    x.cmd("mouse", type="up", x=p["x"] - 10, y=p["y"] + 60)
    s = x.state(); check("rubber band selection stays", s["sel"] == ["a2.txt", "a10.txt", "data.json"] and s["drag"] == "None", s["sel"])
    # where a drop would go
    r = x.cmd("drop_at", id="Row(0)")
    check("drop on a folder row goes into that folder", r["path"] == os.path.join(d, "Alpha") and r["highlight"] == "Row(0)", r)
    x.shot("dragdrop-drop")
    r = x.cmd("drop_at", id="Row(6)")
    check("drop on a file goes into the open folder", r["path"] == d and r["highlight"] == "List", r)
    r = x.cmd("drop_at", id="Nav(1)")
    check("drop on the sidebar", r["path"] and r["path"].lower().endswith("downloads") and r["highlight"] == "Nav(1)", r)
    r = x.cmd("drop_at", id="Back")
    check("no drop on a button", r["path"] is None and r["highlight"] is None, r)
    r = x.cmd("drop_at", leave=True)
    check("highlight cleared when the drag leaves", r["highlight"] is None, r)
    x.nav("pc")
    r = x.cmd("drop_at", id="Row(0)")
    check("drop on a drive in This PC", r["path"] == "C:\\", r)
finally:
    x.close()
check.done()
